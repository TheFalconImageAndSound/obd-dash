// Offline descriptions for common generic (SAE J2012) OBD-II trouble codes.
// Manufacturer-specific codes (P1xxx, etc.) vary by make and aren't listed.

const C = {};
const add = (code, text) => {
  C[code] = text;
};
const p = (n) => 'P' + String(n).padStart(4, '0');

// --- Families generated from patterns -------------------------------------

// Camshaft actuator / timing (bank 1: P0010-P0015, bank 2: P0020-P0025)
for (const [start, bank] of [
  [10, 1],
  [20, 2],
]) {
  add(p(start), `"A" Camshaft Position Actuator Circuit (Bank ${bank})`);
  add(p(start + 1), `"A" Camshaft Position – Timing Over-Advanced or System Performance (Bank ${bank})`);
  add(p(start + 2), `"A" Camshaft Position – Timing Over-Retarded (Bank ${bank})`);
  add(p(start + 3), `"B" Camshaft Position Actuator Circuit (Bank ${bank})`);
  add(p(start + 4), `"B" Camshaft Position – Timing Over-Advanced or System Performance (Bank ${bank})`);
  add(p(start + 5), `"B" Camshaft Position – Timing Over-Retarded (Bank ${bank})`);
}

// O2 sensor heater control circuits
for (const [start, bank, sensor] of [
  [30, 1, 1],
  [36, 1, 2],
  [50, 2, 1],
  [56, 2, 2],
]) {
  const loc = `(Bank ${bank} Sensor ${sensor})`;
  add(p(start), `O2 Sensor Heater Control Circuit ${loc}`);
  add(p(start + 1), `O2 Sensor Heater Control Circuit Low ${loc}`);
  add(p(start + 2), `O2 Sensor Heater Control Circuit High ${loc}`);
}

// O2 sensor circuits
for (const [start, bank, sensor] of [
  [130, 1, 1],
  [136, 1, 2],
  [142, 1, 3],
  [150, 2, 1],
  [156, 2, 2],
  [162, 2, 3],
]) {
  const loc = `(Bank ${bank} Sensor ${sensor})`;
  [
    'O2 Sensor Circuit',
    'O2 Sensor Circuit Low Voltage',
    'O2 Sensor Circuit High Voltage',
    'O2 Sensor Circuit Slow Response',
    'O2 Sensor Circuit No Activity Detected',
    'O2 Sensor Heater Circuit',
  ].forEach((t, i) => add(p(start + i), `${t} ${loc}`));
}

// Injectors, misfires, ignition coils
add('P0200', 'Injector Circuit/Open');
add('P0300', 'Random/Multiple Cylinder Misfire Detected');
for (let cyl = 1; cyl <= 12; cyl++) {
  add(p(200 + cyl), `Injector Circuit/Open – Cylinder ${cyl}`);
  add(p(300 + cyl), `Cylinder ${cyl} Misfire Detected`);
  add(p(350 + cyl), `Ignition Coil "${'ABCDEFGHIJKL'[cyl - 1]}" Primary/Secondary Circuit`);
}

// Transmission gear ratios
for (let g = 1; g <= 5; g++) add(p(730 + g), `Gear ${g} Incorrect Ratio`);
add('P0736', 'Reverse Incorrect Ratio');

